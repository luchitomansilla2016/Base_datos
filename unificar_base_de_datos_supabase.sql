-- 15. HABILITAR PERMISOS PÚBLICOS (API REST ANON / AUTHENTICATED)
DO $$
DECLARE
  t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'oficios', 'informes', 'memorandum', 'informe_administrativo',
    'decreto', 'carta_informativa', 'devolucion', 'resolucion',
    'comunicacion_telefonica', 'orden_telefonica', 'orden_incorporacion',
    'orden_reincorporacion', 'orden_lactancia', 'orden_gravidez'
  ]
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', t);
    EXECUTE format('DROP POLICY IF EXISTS "Acceso total API %I" ON public.%I;', t, t);
    EXECUTE format('CREATE POLICY "Acceso total API %I" ON public.%I FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);', t, t);
    EXECUTE format('GRANT ALL ON TABLE public.%I TO anon, authenticated, service_role;', t);
  END LOOP;
END $$;

